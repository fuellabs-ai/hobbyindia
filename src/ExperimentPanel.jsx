import React, { useEffect, useRef, useState } from 'react';
import { ArrowUpRight, ChevronDown, RotateCcw } from 'lucide-react';
import './experiment.css';
import StoreTrace from './StoreTrace';
import { safeUrl } from './search';

// Attribution travels with every turn, as one quiet line on the trace. Authored turns
// render the backend's authored-demo contract; live turns render model output as-is.
const AUTHORED_LABEL = 'Authored concept · written by the project team, not HobbyLM';
const LIVE_LABEL = 'Live HobbyLM-1B · experimental · may be wrong';

const host = url => { try { return new URL(url).host; } catch { return url; } };

function Trace({ turn, selected, onSelect, onReveal }) {
  const authored = turn.mode === 'authored';
  const loaded = authored ? turn.scenario?.sources : turn.result?.sources;
  return <div className={`trace ${authored ? '' : 'live'}`}>
    <p className="trace-attribution"><span aria-hidden="true"/>{authored ? AUTHORED_LABEL : LIVE_LABEL}</p>
    <StoreTrace turn={turn} selected={selected} onSelect={onSelect} onReveal={onReveal}/>
    {selected !== null && loaded?.[selected] && <SourceDetail source={loaded[selected]}/>}
  </div>;
}

function SourceDetail({ source }) {
  const date = source.saved_capture_date || source.capture_date?.slice(0, 10);
  return <div className="source-detail">
    <a href={safeUrl(source.url)} target="_blank" rel="noopener noreferrer">{host(source.url)}<ArrowUpRight size={12}/></a>
    <span>{source.locator}{date && ` · saved ${date}`}</span>
    <span className="status">Review status: {source.status || source.approval}</span>
    {source.deadline_caveat && <span className="note">{source.deadline_caveat} No countdown is shown.</span>}
    {source.text && <q>{source.text}</q>}
  </div>;
}

function Handoff({ href, children }) {
  return <a className="handoff" href={safeUrl(href)} target="_blank" rel="noopener noreferrer">{children}<ArrowUpRight size={17}/><span className="sr-only"> (official site, opens in a new tab)</span></a>;
}

function ScenarioCard({ scenario, choice, onChoose, question = '' }) {
  const [rtiFacts, setRtiFacts] = useState({});
  const q = question.toLowerCase();
  const simpleRti = scenario.id === 'central-rti-no-reply' && /central/.test(q) && /(?:3[1-9]|[4-9][0-9]) days/.test(q) && /no (?:reply|response)|haven.t received|not received/.test(q);
  if (simpleRti) {
    const ready = rtiFacts.notice === 'no' && rtiFacts.online === 'yes';
    const uncertain = rtiFacts.notice && rtiFacts.notice !== 'no' || rtiFacts.online && rtiFacts.online !== 'yes';
    const title = ready ? 'Prepare a first appeal' : uncertain ? 'Check the notice or filing route first' : rtiFacts.notice === 'no' ? 'Did you file through Central RTI Online?' : 'Did you receive a fee request or transfer notice?';
    return <div className="step-card">
      <span className="card-kicker">{ready || uncertain ? 'Your next step' : 'One question first'}</span>
      <h4 tabIndex={-1} data-result-heading>{title}</h4>
      {!ready && !uncertain && <div className="clarify"><div role="group" aria-label={title}>{(rtiFacts.notice === 'no' ? [['yes','Yes'],['no','No'],['unsure','I’m not sure']] : [['no','No'],['yes','Yes'],['unsure','I’m not sure']]).map(([value,label])=><button key={value} onClick={()=>setRtiFacts(f=>({...f,[f.notice === 'no' ? 'online' : 'notice']:value}))}>{label}</button>)}</div></div>}
      {ready && <><h5>Why this applies to you</h5><p>You said this is a Central request, more than 30 days have passed without a reply, and confirmed online filing with no fee or transfer notice. This is the ordinary no-reply scenario.</p><h5>Keep ready</h5><ul><li>Your original RTI request and acknowledgement</li><li>The request registration number and original email address</li><li>A short explanation that no reply was received</li></ul><p>Use “Submit First Appeal” on RTI Online. The portal FAQ says no first-appeal fee is charged.</p></>}
      {uncertain && <p>Read your acknowledgement and any notices to confirm the relevant authority and process. A fee or transfer notice, or an offline request, needs a different check before using the ordinary online appeal route.</p>}
      {(ready || uncertain) && <div className="decision-actions">{ready && <Handoff href={safeUrl(scenario.handoff_url)}>Continue to RTI Online</Handoff>}<button className="secondary-action" onClick={()=>setRtiFacts({})}>Change answers</button></div>}
      <details className="response-details"><summary>About this response</summary><p>Prepared by the project team, not generated by HobbyLM. Draft wording pending procedural review.</p>{scenario.sources.map(source=><p key={source.url}><a href={safeUrl(source.url)} target="_blank" rel="noreferrer">Official RTI FAQ</a></p>)}</details>
    </div>;
  }
  const branch = scenario.choices.find(c => c.id === choice);
  return <div className="step-card">
    <span className="card-kicker">Next step</span>
    <h4 tabIndex={-1} data-result-heading>{branch ? branch.next_action : scenario.title}</h4>
    <p>{branch ? branch.explanation : scenario.explanation}</p>
    {!branch && <div className="clarify">
      <p id={`clarify-${scenario.id}`}>{scenario.clarification}</p>
      <div role="group" aria-labelledby={`clarify-${scenario.id}`}>{scenario.choices.map(c => <button key={c.id} aria-pressed={choice === c.id} onClick={() => onChoose(choice === c.id ? null : c.id)}>{c.label}</button>)}</div>
    </div>}
    {branch && <button className="secondary-action" onClick={()=>onChoose(null)}>Change answers</button>}
    <div className="handoff-row">
      <Handoff href={safeUrl(scenario.handoff_url)}>{scenario.handoff_label || 'Open CPGRAMS'}</Handoff>
      <small>This page never signs in, files an appeal or submits anything.</small>
    </div>
    {scenario.sources.some(source => source.deadline_caveat) && <p className="card-note">Deadline note: {scenario.sources.find(source => source.deadline_caveat).deadline_caveat}</p>}
    <details className="response-details"><summary>About this response</summary><p>Written by the project team, not generated by HobbyLM.</p><p className="card-foot">{scenario.procedurally_approved ? 'Procedurally reviewed' : 'Illustrative draft · pending procedural review'} · {scenario.live_browser_used ? 'live browsing used' : 'no live browsing'} · {scenario.model_tool_called ? 'model tool called' : 'no model tool calls'}</p></details>
  </div>;
}

function NotCovered({ title, body, onTryLive, link, kicker = 'Not covered by this concept' }) {
  return <div className="step-card quiet">
    <span className="card-kicker">{kicker}</span>
    <h4 tabIndex={-1} data-result-heading>{title}</h4>
    <p>{body}</p>
    <div className="handoff-row">
      {onTryLive && <button className="secondary-action" onClick={onTryLive}>Try live HobbyLM · experimental</button>}
      {link && <Handoff href={safeUrl(link.href)}>{link.label}</Handoff>}
    </div>
  </div>;
}

function WhichCase({ onPick }) {
  return <div className="step-card">
    <span className="card-kicker">One question first</span>
    <h4 tabIndex={-1} data-result-heading>Which situation is closest?</h4>
    <p>A closed grievance can lead to different next steps. Pick the one that matches yours.</p>
    <div className="clarify"><div role="group" aria-label="Which situation is closest">
      <button onClick={() => onPick('remains')}>The problem remains after closure</button>
      <button onClick={() => onPick('details')}>I need the closure details or a reply</button>
    </div></div>
  </div>;
}

function LiveResult({ result }) {
  return <div className="step-card live">
    <span className="card-kicker">HobbyLM-1B output · unchanged</span>
    <p className="model-output" tabIndex={-1} data-result-heading>{result.output || '(The model returned an empty response.)'}</p>
    <details className="evidence drawer">
      <summary>Experiment details<ChevronDown size={16}/></summary>
      <p className="provenance">{result.usage?.input_tokens} input tokens · {result.usage?.output_tokens} output tokens · {result.seconds?.toFixed(1)} seconds{result.finish_reason === 'output_limit' ? ' · stopped at the output limit' : ''}{result.stored === false ? ' · not stored' : ''}</p>
      {result.prompt && <pre>{result.prompt}</pre>}
    </details>
  </div>;
}

function Feedback() {
  const [value, setValue] = useState('');
  return <div className="turn-feedback" role="group" aria-label="Rate this response">{['Helpful', 'Partly helpful', 'Not helpful'].map(label => <button key={label} aria-pressed={value === label} onClick={() => setValue(v => v === label ? '' : label)}>{label}</button>)}<small>{value ? 'Selected in this tab only; not saved.' : 'Feedback stays in this tab.'}</small></div>;
}

function Turn({ turn, onChoose, onPickCase, onTryLive, onRetry }) {
  const ref = useRef(null);
  const [source, setSource] = useState(null);
  // Result cards appear when the trace's signal reaches the answer (immediately with reduced motion).
  const [revealed, setRevealed] = useState(false);
  const show = turn.status === 'done' && revealed;
  useEffect(() => { if (show || turn.status === 'error') ref.current?.querySelector('[data-result-heading]')?.focus({ preventScroll: true }); }, [show, turn.status, turn.kind]);
  return <article className="turn" ref={ref} aria-busy={turn.status === 'working' || (turn.status === 'done' && !revealed)}>
    <p className="turn-question"><span className="sr-only">Your question: </span>{turn.question}</p>
    <Trace turn={turn} selected={source} onSelect={setSource} onReveal={() => setRevealed(true)}/>
    {turn.status === 'error' && <div className="step-card error" role="alert"><span className="card-kicker">Could not complete</span><p>{turn.error}</p><button className="secondary-action" onClick={onRetry}><RotateCcw size={15}/>Try again</button></div>}
    {show && turn.kind === 'scenario' && <ScenarioCard scenario={turn.scenario} question={turn.question} choice={turn.choice} onChoose={onChoose}/>}
    {show && turn.kind === 'which_case' && <WhichCase onPick={onPickCase}/>}
    {show && turn.kind === 'details' && <NotCovered title="No authored next step for closure details yet" body="This concept only prepares the case where a closed Central grievance still has an unresolved problem. The saved CPGRAMS FAQ discusses requests for closure details separately; that answer still needs procedural review before it appears here." link={{ href: 'https://pgportal.gov.in/Home/Faq', label: 'Read the CPGRAMS FAQ' }}/>}
    {show && turn.kind === 'state' && <NotCovered title="This concept covers Central grievances only" body="The prepared scenario is about Central Ministry/Department grievances on CPGRAMS. State and UT grievance routes differ and are not covered here." onTryLive={onTryLive}/>}
    {show && turn.kind === 'not_covered' && <NotCovered title="This concept doesn’t cover that question" body="The authored preview covers prepared CPGRAMS and RTI scenarios. It won’t force that answer onto other questions." onTryLive={onTryLive}/>}
    {show && turn.kind === 'live' && <LiveResult result={turn.result}/>}
    {show && turn.kind === 'live_refused' && <NotCovered kicker="Declined by the live experiment" title="The live experiment doesn’t cover that question" body={turn.refusal || 'The local experiment declined this question.'} link={{ href: 'https://www.india.gov.in/', label: 'Start from india.gov.in' }}/>}
    {show && <Feedback/>}
  </article>;
}

export default function ExperimentPanel({ turns, busy, live, onLiveChange, onReset, onChoose, onPickCase, onTryLive, onRetry }) {
  if (!turns.length) return null;
  return <section className="next-panel" id="next-step" aria-labelledby="next-step-title">
    <div className="step-head">
      <h2 id="next-step-title">Your next step</h2>
      <div className="next-tools">
        <button role="switch" aria-checked={live} className="live-switch" onClick={() => onLiveChange(!live)}><span aria-hidden="true"/>Try live HobbyLM · experimental</button>
        <button className="secondary-action" onClick={onReset} disabled={busy}>New conversation</button>
      </div>
    </div>
    <p className="next-note">{live ? 'Live mode applies to your next question. The local 1B model may be wrong, and it does not learn from this conversation.' : ''} Don’t share personal details.</p>
    {turns.map(turn => <Turn key={turn.id} turn={turn} onChoose={choice => onChoose(turn.id, choice)} onPickCase={c => onPickCase(turn.id, c)} onTryLive={() => onTryLive(turn.question)} onRetry={() => onRetry(turn)}/>)}
    <p className="sr-only" role="status" aria-live="polite">{busy ? (live ? 'Waiting for HobbyLM output.' : 'Opening saved evidence.') : ''}</p>
  </section>;
}
